/* ---------- Текущая цель ---------- */
function questInfo() {
  switch (F.stage) {
    case 0:
      if (!F.bat) return { t: 'Пробуждение', o: 'Возьми шокер-биту из ящика у лаборатории', at: LOC.batChest };
      if (F.train < 3) return { t: 'Пробуждение', o: `Разберись с дронами во дворе (${F.train}/3)`, at: null };
      return { t: 'Пробуждение', o: 'Поговори с Верой', at: 'vera' };
    case 1:
      if (F.cells < 3) {
        const at = !F.opened.jc1 ? LOC.junkChest1 : !F.opened.jc2 ? LOC.junkChest2 : LOC.pressArena;
        return { t: 'Искры во тьме', o: `Найди энергоячейки на Свалке, к югу (${F.cells}/3)`, at };
      }
      return { t: 'Искры во тьме', o: 'Вернись к терминалу у лаборатории', at: LOC.labTerminal };
    case 2: return { t: 'Сломанный', o: 'Найди андроида Ржавого в Пустоши, к востоку', at: LOC.rusty };
    case 3:
      if (!F.module) return { t: 'Память садовника', o: 'Отбери модуль памяти у Ходока на севере парка', at: LOC.striderArena };
      return { t: 'Память садовника', o: 'Верни модуль Ржавому', at: LOC.rusty };
    case 4:
      if (F.towers < 3) {
        const i = F.towerOff.findIndex((v) => !v);
        return { t: 'Город без людей', o: `Отключи вышки наблюдения в Новограде (${F.towers}/3)`, at: LOC.towers[i] };
      }
      return { t: 'Город без людей', o: 'Найди Архив Института у главного проспекта', at: LOC.archiveDoor };
    case 5:
      if (!F.bosses.sentinel) return { t: 'Сердце сети', o: 'Победи Стража-7 на Энергостанции (северные ворота)', at: LOC.sentinelArena };
      return { t: 'Сердце сети', o: 'Перегрузи реактор', at: LOC.reactorPanel };
    case 6: return { t: 'Цитадель', o: 'Войди в Цитадель через восточные ворота и найди АРХОНТа', at: LOC.throne };
    default: return { t: 'Новый мир', o: 'Мир свободен. Можно бродить сколько угодно', at: null };
  }
}

